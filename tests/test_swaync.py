"""SwayNC schema, GTK CSS and action safety checks; never change host audio/power."""
import importlib.util
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / '.config/swaync'
SCHEMA = Path('/etc/xdg/swaync/configSchema.json')


class SwayNCTests(unittest.TestCase):
    def setUp(self):
        self.config = json.loads((CONFIG / 'config.json').read_text())

    @unittest.skipUnless(SCHEMA.exists() and importlib.util.find_spec('jsonschema'), 'SwayNC schema and python-jsonschema required')
    def test_installed_schema_including_all_widgets(self):
        import jsonschema
        schema = json.loads(SCHEMA.read_text())
        errors = list(jsonschema.Draft202012Validator(schema).iter_errors(self.config))
        self.assertEqual(errors, [], '\n'.join(str(error) for error in errors))

    def test_no_deprecated_sizing_or_unsupported_widget_options(self):
        self.assertNotIn('notification-icon-size', self.config)
        mpris = self.config['widget-config']['mpris']
        self.assertNotIn('image-size', mpris)
        self.assertNotIn('image-radius', mpris)
        self.assertTrue(mpris['autohide'])
        self.assertEqual(self.config['control-center-width'], 378)
        self.assertEqual(self.config['control-center-height'], 1100)
        self.assertTrue(self.config['widget-config']['notifications']['vexpand'])
        self.assertEqual(self.config['timeout-critical'], 0)

    def test_grid_has_labels_complete_rows_and_state_queries(self):
        grid = self.config['widget-config']['buttons-grid']
        self.assertEqual(grid['buttons-per-row'], 3)
        self.assertEqual(len(grid['actions']) % grid['buttons-per-row'], 0)
        for action in grid['actions']:
            self.assertRegex(action['label'], r'[A-Za-z]{3,}')
            self.assertNotIn('hyprctl dispatch exit', action['command'])
            self.assertNotIn('AirplaneMode', action['command'])
            for command in [action['command'], action.get('update-command', '')]:
                result = subprocess.run(['sh', '-n', '-c', command], capture_output=True, text=True)
                self.assertEqual(result.returncode, 0, result.stderr)
            if action.get('type') == 'toggle':
                self.assertIn('status-', action['update-command'])

    def test_widget_order_has_header_first_history_last(self):
        self.assertEqual(self.config['widgets'][0], 'title')
        self.assertEqual(self.config['widgets'][-1], 'notifications')
        self.assertEqual(set(self.config['widgets']), set(self.config['widget-config']))

    def test_original_background_and_generated_palette_preserved(self):
        css = (CONFIG / 'style.css').read_text()
        self.assertIn('@define-color noti-bg #0e0e16;', css)
        block = re.search(r'\.control-center\s*\{([^}]+)\}', css)[1]
        self.assertIn('background: @noti-bg;', block)
        self.assertEqual(css.count('/* ==== GENERATED by sync-colors.sh'), 1)
        self.assertIn('--notification-icon-size: 40px;', css)
        self.assertNotIn('font-size: 0.1rem', css)
        actions = re.search(r'\.notification-action > button\s*\{([^}]+)\}', css)[1]
        self.assertIn('background: @noti-bg;', actions)
        self.assertIn('background-image: none;', actions)
        scrollbar = re.search(r'\.control-center scrollbar slider\s*\{([^}]+)\}', css)[1]
        self.assertIn('opacity: 0;', scrollbar)
        self.assertIn('min-width: 0;', scrollbar)

    @unittest.skipUnless(importlib.util.find_spec('gi'), 'GTK4 Python bindings required')
    def test_real_gtk4_css_parser(self):
        import gi
        try:
            gi.require_version('Gtk', '4.0')
            from gi.repository import Gtk
        except (ImportError, ValueError):
            self.skipTest('GTK4 is not installed')
        provider = Gtk.CssProvider()
        errors = []
        provider.connect('parsing-error', lambda _provider, _section, error: errors.append(str(error)))
        provider.load_from_path(str(CONFIG / 'style.css'))
        self.assertEqual(errors, [])

    def test_audio_toggles_set_desired_state_and_opening_panel_is_read_only(self):
        with tempfile.TemporaryDirectory() as temp:
            path = Path(temp) / 'pamixer'
            path.write_text('''#!/bin/sh
case "$*" in
    *--get-mute*) printf '%s\\n' "$MOCK_AUDIO_STATE" ;;
    *) printf '<%s>' "$@" ;;
esac
''')
            path.chmod(0o755)
            for target, source in [('output', ''), ('input', '<--default-source>')]:
                for state in ('true', 'false'):
                    env = {**os.environ, 'PATH': temp, 'MOCK_AUDIO_STATE': state, 'SWAYNC_TOGGLE_STATE': state}
                    status = subprocess.run(['/bin/bash', str(CONFIG / 'actions.sh'), 'status-' + target], env=env, capture_output=True, text=True)
                    self.assertEqual(status.returncode, 0, status.stderr)
                    self.assertEqual(status.stdout.strip(), state)
                    action = subprocess.run(['/bin/bash', str(CONFIG / 'actions.sh'), 'mute-' + target], env=env, capture_output=True, text=True)
                    self.assertEqual(action.returncode, 0, action.stderr)
                    self.assertEqual(action.stdout, source + ('<--mute>' if state == 'true' else '<--unmute>'))
            env['SWAYNC_TOGGLE_STATE'] = 'invalid'
            action = subprocess.run(['/bin/bash', str(CONFIG / 'actions.sh'), 'mute-output'], env=env, capture_output=True, text=True)
            self.assertEqual(action.returncode, 2)
            self.assertEqual(action.stdout, '')
            env['MOCK_AUDIO_STATE'] = 'invalid'
            action = subprocess.run(['/bin/bash', str(CONFIG / 'actions.sh'), 'status-output'], env=env, capture_output=True, text=True)
            self.assertEqual(action.returncode, 1)

    def test_repo_mirror_is_identical(self):
        for name in ('config.json', 'style.css', 'actions.sh'):
            self.assertEqual((CONFIG / name).read_bytes(), (ROOT / 'base-dots/config/swaync' / name).read_bytes())
